import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "data", "live-snapshot.json");
const outputPath = path.join(root, "miniprogram", "data", "live-snapshot.js");
const snapshot = JSON.parse(await readFile(sourcePath, "utf8"));
const require = createRequire(import.meta.url);
const { sanitizeSnapshot } = require("../cloudfunctions/aurum-data/sanitize.js");
const publicSnapshot = sanitizeSnapshot(snapshot);

const HISTORY_LIMIT = 24;

function sampleNumbers(values, limit = HISTORY_LIMIT) {
  if (!Array.isArray(values) || values.length <= limit) return values;
  const last = values.length - 1;
  return Array.from({ length: limit }, (_, index) => {
    const sourceIndex = Math.round((index / Math.max(1, limit - 1)) * last);
    return values[sourceIndex];
  });
}

function sampleSeries(entries, limit = HISTORY_LIMIT) {
  if (!Array.isArray(entries) || entries.length <= limit) return entries;
  const last = entries.length - 1;
  return Array.from({ length: limit }, (_, index) => {
    const sourceIndex = Math.round((index / Math.max(1, limit - 1)) * last);
    return entries[sourceIndex];
  });
}

function slimForMiniProgram(data) {
  const next = structuredClone(data);
  if (next.us && Array.isArray(next.us.stocks)) {
    next.us.stocks = next.us.stocks.map((stock) => ({
      ...stock,
      history: sampleNumbers(stock.history, HISTORY_LIMIT),
    }));
  }
  if (next.gold && next.gold.history) {
    next.gold.history = {
      ...next.gold.history,
      international: sampleSeries(next.gold.history.international, HISTORY_LIMIT),
      domestic: sampleSeries(next.gold.history.domestic, HISTORY_LIMIT),
    };
  }
  return next;
}

const slimSnapshot = slimForMiniProgram(publicSnapshot);

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `// Generated by scripts/sync-miniprogram-data.mjs. Do not edit manually.\nmodule.exports = ${JSON.stringify(slimSnapshot)};\n`,
);

